"""DNA regions, motif sites, protein readers, and the RNA-making machinery."""
from chapter_drawing import *

def build_figure():
    d=ChapterDrawing('F10',150,'调控序列与读取它们的蛋白质','把区域、短序列与蛋白质放进同一最小工作模型')
    d.heading('title','谁提供信息，谁真正制造 RNA？',(7,140))
    d.region('enhancer.region',18,74,50,ENH)
    d.region('promoter.region',110,74,18,PROM)
    d.region('gene.region',129,74,30,GENE)
    d.line('dna.upper',[(9,77.2),(161,77.2)],color=DNA)
    d.line('dna.lower',[(9,70.8),(161,70.8)],color=DNA)
    for i,(xx,letter) in enumerate([(28,'A'),(43,'B'),(58,'C')]):
        d.motif(f'motif.{i}',xx,74,letter)
        d.protein(f'tf.{i}',xx,84,letter)
        d.line(f'binding.{i}',[(xx,78.8),(xx,78.1)],color=MUTED,width=.8)
    d.text('tf.label','转录因子（蛋白质）',(43,116))
    d.ellipse('machinery.shape',(132,95),43,14,color=MACHINE,weight=.12,role='protein')
    d.text('machinery.label','转录机器',(132,95))
    d.text('polymerase.label','含 RNA 聚合酶',(132,111),size=NOTE)
    d.edge('assembly',(119,87),(119,80),kind='template')
    d.edge('possible.cooperation',(65,95),(109,95),kind='conditional',rad=-.45)
    d.text('influence.label','可能影响',(87,111),size=NOTE)
    xx=np.linspace(118,153,70)
    d.line('rna.product',np.c_[xx,127+1.3*np.sin((xx-118)*.7)],color=SECONDARY,width=1.5)
    d.text('rna.label','RNA',(135,137),size=NOTE)
    d.edge('rna.synthesis',(152,98),(153,122),kind='process')
    d.edge('transcription.direction',(133,65),(156,65),kind='process')
    d.line('start.marker',[(129,69),(129,79)],color=INK,width=.8)
    d.text('dna.label','DNA',(13,64),size=NOTE)
    d.text('start.label','转录起点',(134,46),size=NOTE)
    d.line('start.guide',[(129,68),(129,51)],color=MUTED,width=.8)
    d.text('enhancer.label','增强子',(43,57))
    d.text('promoter.label','启动子',(119,57))
    d.text('gene.label','基因',(146,57))
    d.text('motif.definition','A / B / C：增强子内部的短识别位置（结合基序）',(85,40),size=NOTE)
    d.text('material.distinction','框在 DNA 上：调控区域　　框上方：蛋白质',(85,27),size=NOTE)
    d.note('弧形虚线表示可能影响；远端协作的空间条件见图 F12。',y=10)
    return d.result()

if __name__=='__main__':export(build_figure(),__file__)
